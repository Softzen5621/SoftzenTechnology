const assignFeesToClass =
async ({

  schoolId,

  academicYear,

  className,

  section = "ALL",

  createdBy

}) => {

  try {

    // ======================
    // FILTER
    // ======================

    const filter = {
  schoolId,
  currentClassName: className,
  studentStatus: "ACTIVE",
  isDeleted: false
};



    // ======================
    // SECTION FILTER
    // ======================

    if (

      section &&

      section !== "ALL"

    ) {

      filter.currentSection =
        section;
    }



    // ======================
    // STUDENTS
    // ======================
console.log(
  "FILTER =",
  filter
);
console.log("ASSIGN CLASS START");
console.log("CLASS =", className);
console.log("ACADEMIC YEAR =", academicYear);
console.log("FILTER =", filter);

const students = await Student.find(filter);

console.log("STUDENTS FOUND =", students.length);

students.forEach((s) => {
  console.log(
    s.name,
    s.currentClassName,
    s.studentStatus
  );
});


    // ======================
    // NO STUDENTS
    // ======================

    if (
      students.length === 0
    ) {

      return {

        success: false,

        message:
          "No students found"
      };
    }



    // ======================
    // LOOP
    // ======================

    const assignedStudents =
      [];



    for (

      const student
      of students

    ) {

      try {

        const profile =

          await assignFeesToStudent({

            schoolId,

            academicYear,

            student,

            createdBy
          });




        assignedStudents.push({

          studentId:
            student._id,

          name:
            student.fullName ||

            student.name,

          profileId:
            profile._id
        });

      } catch (error) {

        console.error(

          `FAILED FOR STUDENT ${student._id}`,

          error.message
        );
      }
    }



    return {

      success: true,



      totalStudents:
        students.length,



      assignedCount:
        assignedStudents.length,



      assignedStudents
    };

  } catch (error) {

    console.error(

      "CLASS ASSIGNMENT ERROR:",

      error
    );

    throw error;
  }
};



