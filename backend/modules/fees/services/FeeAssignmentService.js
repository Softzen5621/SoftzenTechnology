// ======================
// ASSIGN FEES TO STUDENT
// ======================
const assignFeesToStudent =
async ({

  schoolId,
  academicYear,
  student,
  createdBy

}) => {

  console.log(
    "ASSIGNING STUDENT =",
    student.name,
    student.currentClassName
  );

  try {    // ======================
    // FIND ACTIVE STRUCTURE
    // ======================

    const feeStructure =
      await FeeStructure.findOne({
        

        schoolId,

        academicYear,

        className:
          student.currentClassName,

        $or: [

          {

          section:
  student.currentSection || ""
          },

          {

            section:
              "ALL"
          }
        ],

        status: "ACTIVE",

        isDeleted: false
      });

      console.log(
  "FEE STRUCTURE FOUND =",
  feeStructure
);




    // ======================
    // NO STRUCTURE
    // ======================

    if (!feeStructure) {

      throw new Error(
        "No active fee structure found"
      );
    }



    // ======================
    // PREVENT DUPLICATE
    // ======================

    const existingProfile =
      await StudentFeeProfile.findOne({

        schoolId,

        academicYear,

        studentId:
          student._id,

        isDeleted: false
      });




    if (existingProfile) {

      return existingProfile;
    }



    // ======================
    // GENERATE ASSIGNMENTS
    // ======================

    const feeAssignments =
      feeStructure.feeItems.map(

        (item) => {

          // ======================
          // DUE DATE
          // ======================

          const dueDate =
            new Date();




          if (
            item.dueDay
          ) {

            dueDate.setDate(
              item.dueDay
            );
          }



          return {

            feeStructureId:
              feeStructure._id,



          categoryId:
  item.categoryId || null,



            title:
              item.title,



            code:
              item.code,



            amount:
              item.amount,



            recurringType:
              item.recurringType,



            mandatory:
              item.mandatory,



            dueDate,



            allowInstallments:
              item.installmentAllowed,



            lateFineEnabled:
              item.lateFineEnabled,



            lateFineAmount:
              item.lateFineAmount,



            // ======================
            // PAYMENT TRACKING
            // ======================

            paidAmount: 0,



            pendingAmount:
              item.amount,



            discountAmount: 0,



            fineAmount: 0,



            status:
              "PENDING",



            paymentStatus:
              "UNPAID"
          };
        }
      );



    // ======================
    // CREATE PROFILE
    // ======================

console.log("BEFORE CREATE");

const profile =
  await StudentFeeProfile.create({
    schoolId,
    academicYear,
    studentId: student._id,
    className: student.currentClassName,
    section: student.currentSection,
    rollNumber: student.rollNumber,
    feeAssignments,
    createdBy,
    autoGenerated: true,
    isDeleted: false
  });

console.log("PROFILE CREATED");
console.log(profile);


    return profile;

  } catch (error) {

  console.error(
    "FEE ASSIGNMENT ERROR:"
  );

  console.error(error);

  console.error(error.message);

  if (error.errors) {
    console.error(error.errors);
  }

  throw error;
}
};



